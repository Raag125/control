// Helper functions for easy lookup across the application
export const getAllServices = () => {
  if (typeof window !== 'undefined') {
    try {
      const stored = JSON.parse(localStorage.getItem('azt_services'))
      if (stored && stored.length > 0) return stored
    } catch {}
  }
  return SERVICES_DATA
}

export const getServiceBySlug = (slug) => {
  if (!slug) return null
  const normalized = slug.startsWith('/') ? slug.slice(1) : slug
  const all = getAllServices()
  return all.find((s) => s.slug === normalized || s.id === normalized || s.path === `/${normalized}` || s.path === slug)
}

export const getServicesByCategory = (category) => {
  const all = getAllServices()
  return all.filter((s) => s.category === category)
}

export default SERVICES_DATA


